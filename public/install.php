<?php
/**
 * Installation wizard (delete or rename this file after a successful install).
 *
 * Creates app/config/env.php, installs the MySQL schema and optionally seeds the
 * demo dataset. Runs on plain PHP 7.4+ (no extensions beyond pdo_mysql).
 */
declare(strict_types=1);

$root = dirname(__DIR__);
$envFile = $root . '/app/config/env.php';
$installed = is_file($envFile);

function h($value): string
{
    return htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8');
}

$errors = [];
$success = null;
$logs = [];
$action = $_POST['action'] ?? '';

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $driver = 'mysql';
    $host = trim((string) ($_POST['db_host'] ?? '127.0.0.1'));
    $port = trim((string) ($_POST['db_port'] ?? '3306'));
    $name = trim((string) ($_POST['db_name'] ?? ''));
    $user = trim((string) ($_POST['db_user'] ?? ''));
    $pass = (string) ($_POST['db_pass'] ?? '');
    $url  = rtrim(trim((string) ($_POST['app_url'] ?? '')), '/');
    $seed = isset($_POST['seed']);
    $demo = isset($_POST['demo_mode']);

    foreach (['PHP >= 7.4' => version_compare(PHP_VERSION, '7.4', '>=')] as $label => $ok) {
        if (!$ok) {
            $errors[] = 'Persyaratan gagal: ' . $label;
        }
    }
    if (!class_exists('PDO')) {
        $errors[] = 'Ekstensi PDO tidak aktif.';
    }
    if (!in_array('mysql', PDO::getAvailableDrivers(), true)) {
        $errors[] = 'Driver pdo_mysql tidak aktif. Aktifkan ekstensi php-mysql.';
    }
    foreach (['storage', 'storage/uploads', 'storage/logs', 'storage/cache'] as $dir) {
        $path = $root . '/' . $dir;
        if (!is_dir($path)) {
            @mkdir($path, 0775, true);
        }
        if (!is_writable($path)) {
            $errors[] = 'Folder ' . $dir . ' harus writable (chmod 775).';
        }
    }
    if ($name === '' || $user === '') {
        $errors[] = 'Nama database dan user wajib diisi.';
    }

    if (!$errors) {
        try {
            $pdo = new PDO(
                sprintf('mysql:host=%s;port=%s;charset=utf8mb4', $host, $port ?: '3306'),
                $user,
                $pass,
                [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]
            );
            $pdo->exec('CREATE DATABASE IF NOT EXISTS `' . str_replace('`', '', $name) . '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');
            $logs[] = 'Database `' . $name . '` siap.';

            $pdo->exec('USE `' . str_replace('`', '', $name) . '`');
            $schema = file_get_contents($root . '/database/schema.sql');
            $statements = array_filter(array_map('trim', preg_split('/;\s*(\n|$)/', preg_replace('/^\s*--.*$/m', '', (string) $schema) ?: []) ?: []));
            foreach ($statements as $statement) {
                if ($statement !== '') {
                    $pdo->exec($statement);
                }
            }
            $logs[] = count($statements) . ' statement skema dieksekusi.';

            $env = "<?php\n// Generated by installer on " . date('Y-m-d H:i:s') . "\nreturn [\n";
            $pairs = [
                'app_env'     => 'production',
                'app_url'     => $url,
                'app_key'     => bin2hex(random_bytes(16)),
                'db_driver'   => $driver,
                'db_host'     => $host,
                'db_port'     => $port ?: '3306',
                'db_database' => $name,
                'db_username' => $user,
                'db_password' => $pass,
                'demo_mode'   => $demo ? true : false,
            ];
            foreach ($pairs as $key => $value) {
                $env .= "    '" . $key . "' => " . var_export($value, true) . ",\n";
            }
            $env .= "];\n";
            file_put_contents($envFile, $env);
            $logs[] = 'Konfigurasi disimpan pada app/config/env.php.';

            if ($seed) {
                require $root . '/app/bootstrap.php';
                $seedLog = \App\Core\Schema::seed(true);
                $logs = array_merge($logs, $seedLog);
            }

            $success = 'Instalasi selesai. Hapus atau rename public/install.php sebelum produksi.';
            $installed = true;
        } catch (Throwable $e) {
            $errors[] = 'Instalasi gagal: ' . $e->getMessage();
        }
    }
}
