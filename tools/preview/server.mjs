// PHP info endpoint (used for diagnostics).
php.writeFile('/www/public/_status.php', '<?php echo json_encode(["php"=>PHP_VERSION,"sapi"=>PHP_SAPI,"ext"=>get_loaded_extensions()]);');

function serveStatic(req, res, urlPath) {
  const safePath = path.normalize(decodeURIComponent(urlPath)).replace(/^(\.\.[/\\])+/, '');
  const filePath = path.join(PUBLIC_DIR, safePath);
  if (!filePath.startsWith(PUBLIC_DIR)) return false;
  try {
    const stat = fs.statSync(filePath);
    if (stat.isFile()) {
      const ext = path.extname(filePath).toLowerCase();
      res.writeHead(200, {
        'Content-Type': MIME[ext] || 'application/octet-stream',
        'Content-Length': stat.size,
        'Cache-Control': ext === '.php' ? 'no-store' : 'public, max-age=300',
      });
      fs.createReadStream(filePath).pipe(res);
      return true;
    }
  } catch {
    /* not a static file */
  }
  return false;
}

async function readBody(req) {
  const chunks = [];
  for await (const chunk of req) chunks.push(chunk);
  return Buffer.concat(chunks);
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://${req.headers.host || 'localhost'}`);
  const urlPath = url.pathname;

  if (!urlPath.endsWith('.php') && serveStatic(req, res, urlPath)) return;
  if (urlPath === '/') {
    // let PHP handle the dashboard/login redirect logic
  }

  try {
    const bodyBuffer = await readBody(req);
    const headers = {};
    for (const [key, value] of Object.entries(req.headers)) {
      if (value === undefined) continue;
      headers[key] = Array.isArray(value) ? value.join('; ') : value;
    }

    // Parse the body in node: the wasm SAPI cannot parse it per request.
    const post = {};
    const contentType = (headers['content-type'] || '').toLowerCase();
    if (bodyBuffer.length > 0) {
      if (contentType.includes('application/x-www-form-urlencoded') || contentType === '') {
        for (const [key, value] of new URLSearchParams(bodyBuffer.toString('utf8'))) post[key] = value;
      } else if (contentType.includes('application/json')) {
        try {
          const parsed = JSON.parse(bodyBuffer.toString('utf8'));
          if (parsed && typeof parsed === 'object') Object.assign(post, parsed);
        } catch { /* ignore */ }
      }
    }

    const context = {
      method: req.method,
      uri: req.url,
      headers,
      post,
      ip: req.socket.remoteAddress || '127.0.0.1',
    };
    php.writeFile('/www/storage/cache/request.json', JSON.stringify(context));

    const response = await handler.request({
      url: '/_router.php',
      method: req.method,
      headers: { host: headers.host || 'localhost' },
      body: undefined,
    });

    const responseHeaders = { ...(response.headers || {}) };
    const cookies = responseHeaders['set-cookie'] || responseHeaders['Set-Cookie'];
    delete responseHeaders['set-cookie'];
    delete responseHeaders['Set-Cookie'];
    // keep-alive is managed by node
    delete responseHeaders['connection'];
    delete responseHeaders['Connection'];

    let payload;
    if (response.bytes) {
      payload = Buffer.from(response.bytes);
    } else {
      payload = Buffer.from(response.text || '', 'utf8');
    }
    if (!responseHeaders['content-type'] && !responseHeaders['Content-Type']) {
      responseHeaders['Content-Type'] = 'text/html; charset=utf-8';
    }
    if (payload.length) responseHeaders['Content-Length'] = payload.length;

    if (cookies) {
      responseHeaders['set-cookie'] = Array.isArray(cookies) ? cookies : [cookies];
    }
    res.writeHead(response.httpStatusCode || 200, responseHeaders);
    res.end(payload);
  } catch (error) {
    console.error('[preview] error', error);
    res.writeHead(500, { 'Content-Type': 'text/html; charset=utf-8' });
    res.end(
      '<pre style="font:13px/1.5 monospace;padding:20px;background:#0b2135;color:#ffb4c0;white-space:pre-wrap">' +
        'PHP preview error\n\n' +
        String(error && error.stack ? error.stack : error).replace(/[<>&]/g, (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;' }[c])) +
        '</pre>'
    );
  }
});

server.listen(PORT, HOST, () => {
  console.log(`[preview] HRIS Asia Raya listening on http://${HOST}:${PORT}`);
});

process.on('unhandledRejection', (err) => console.error('[preview] unhandled', err));
