function serveStatic(req, res, urlPath) {
  const safePath = path.normalize(decodeURIComponent(urlPath)).replace(/^(\.\.[/\\])+/, '');
  const filePath = path.join(PUBLIC_DIR, safePath);
  if (!filePath.startsWith(PUBLIC_DIR)) return false;
  try {
    const stat = fs.statSync(filePath);
    if (stat.isFile()) {
      const ext = path.extname(filePath).toLowerCase();
      res.writeHead(200, {
        'Content-Type': MIME[ext] || 'application/octet-stream',
        'Content-Length': stat.size,
        'Cache-Control': ext === '.php' ? 'no-store' : 'public, max-age=300',
      });
      fs.createReadStream(filePath).pipe(res);
      return true;
    }
  } catch {
    /* not a static file */
  }
  return false;
}

async function readBody(req) {
  const chunks = [];
  for await (const chunk of req) chunks.push(chunk);
  return Buffer.concat(chunks);
}


/**
 * Minimal multipart/form-data parser (the wasm SAPI cannot populate $_FILES).
 * Files are written to storage/cache/tmp and exposed to PHP through the
 * request context; the request router rebuilds $_FILES from it.
 */
function parseMultipart(buffer, boundary) {
  const result = { fields: {}, files: {} };
  const delimiter = Buffer.from('--' + boundary);
  const parts = [];
  let start = buffer.indexOf(delimiter);
  if (start === -1) return result;
  start += delimiter.length;
  while (start < buffer.length) {
    // after boundary: either '--' (end) or CRLF then part
    if (buffer.slice(start, start + 2).toString() === '--') break;
    if (buffer.slice(start, start + 2).toString() === '\r\n') start += 2;
    const end = buffer.indexOf(delimiter, start);
    if (end === -1) break;
    parts.push(buffer.slice(start, end - 2)); // strip trailing CRLF
    start = end + delimiter.length;
  }

  const tmpDir = path.join(ROOT, 'storage', 'cache', 'tmp');
  fs.mkdirSync(tmpDir, { recursive: true });

  for (const part of parts) {
    const split = part.indexOf('\r\n\r\n');
    if (split === -1) continue;
    const rawHeaders = part.slice(0, split).toString('utf8');
    const content = part.slice(split + 4);
    const disp = /content-disposition:([^\r\n]+)/i.exec(rawHeaders);
    if (!disp) continue;
    const nameMatch = /name="([^"]*)"/i.exec(disp[1]);
    if (!nameMatch) continue;
    const field = nameMatch[1];
    const fileMatch = /filename="([^"]*)"/i.exec(disp[1]);
    const typeMatch = /content-type:\s*([^\r\n]+)/i.exec(rawHeaders);

    if (!fileMatch || fileMatch[1] === '') {
      assignField(result.fields, field, content.toString('utf8'));
      continue;
    }

    const tmpName = 'upload-' + Date.now().toString(36) + '-' + Math.random().toString(36).slice(2, 10);
    const tmpPath = path.join(tmpDir, tmpName);
    fs.writeFileSync(tmpPath, content);
    result.files[field] = {
      name: fileMatch[1],
      type: typeMatch ? typeMatch[1].trim() : 'application/octet-stream',
      tmp_name: '/www/storage/cache/tmp/' + tmpName,
      size: content.length,
      error: 0,
    };
  }
  return result;
}


/**
 * Assign a form field, mirroring PHP's bracket syntax for the subset we use:
 *   name[]        → array push
 *   name[key]     → nested object
 *   name          → plain value (last one wins, like PHP)
 */
function assignField(target, key, value) {
  const arrayMatch = /^([^\[]+)\[\]$/.exec(key);
  if (arrayMatch) {
    const name = arrayMatch[1];
    if (!Array.isArray(target[name])) target[name] = [];
    target[name].push(value);
    return;
  }
  const nestedMatch = /^([^\[]+)\[([^\]]*)\]$/.exec(key);
  if (nestedMatch) {
    const [, name, sub] = nestedMatch;
    if (!target[name] || typeof target[name] !== 'object' || Array.isArray(target[name])) target[name] = {};
    target[name][sub] = value;
    return;
  }
  target[key] = value;
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://${req.headers.host || 'localhost'}`);
  const urlPath = url.pathname;

  if (!urlPath.endsWith('.php') && serveStatic(req, res, urlPath)) return;
  if (urlPath === '/') {
    // let PHP handle the dashboard/login redirect logic
  }

  try {
    const bodyBuffer = await readBody(req);
    const headers = {};
    for (const [key, value] of Object.entries(req.headers)) {
      if (value === undefined) continue;
      headers[key] = Array.isArray(value) ? value.join('; ') : value;
    }

    // Parse the body in node: the wasm SAPI cannot parse it per request.
    const post = {};
    const files = {};
    const contentType = (headers['content-type'] || '').toLowerCase();
    if (bodyBuffer.length > 0) {
      if (contentType.includes('multipart/form-data')) {
        const boundaryMatch = /boundary=(?:"([^"]+)"|([^;]+))/i.exec(contentType);
        if (boundaryMatch) {
          const parsed = parseMultipart(bodyBuffer, (boundaryMatch[1] || boundaryMatch[2] || '').trim());
          Object.assign(post, parsed.fields);
          Object.assign(files, parsed.files);
        }
      } else if (contentType.includes('application/x-www-form-urlencoded') || contentType === '') {
        for (const [key, value] of new URLSearchParams(bodyBuffer.toString('utf8'))) assignField(post, key, value);
      } else if (contentType.includes('application/json')) {
        try {
          const parsed = JSON.parse(bodyBuffer.toString('utf8'));
          if (parsed && typeof parsed === 'object') Object.assign(post, parsed);
        } catch { /* ignore */ }
      }
    }

    const context = {
      method: req.method,
      uri: req.url,
      headers,
      post,
      files,
      ip: req.socket.remoteAddress || '127.0.0.1',
    };
    php.writeFile('/www/storage/cache/request.json', JSON.stringify(context));

    const response = await handler.request({
      url: '/_router.php',
      method: req.method,
      headers: { host: headers.host || 'localhost' },
      body: undefined,
    });

    const responseHeaders = { ...(response.headers || {}) };
    const cookies = responseHeaders['set-cookie'] || responseHeaders['Set-Cookie'];
    delete responseHeaders['set-cookie'];
    delete responseHeaders['Set-Cookie'];
    // keep-alive is managed by node
    delete responseHeaders['connection'];
    delete responseHeaders['Connection'];

    let payload;
    if (response.bytes) {
      payload = Buffer.from(response.bytes);
    } else {
      payload = Buffer.from(response.text || '', 'utf8');
    }
    if (!responseHeaders['content-type'] && !responseHeaders['Content-Type']) {
      responseHeaders['Content-Type'] = 'text/html; charset=utf-8';
    }
    if (payload.length) responseHeaders['Content-Length'] = payload.length;

    const jar = cookies ? (Array.isArray(cookies) ? cookies : [cookies]) : [];
    const extra = responseHeaders['x-hris-set-cookies'] || responseHeaders['X-HRIS-Set-Cookies'];
    delete responseHeaders['x-hris-set-cookies'];
    delete responseHeaders['X-HRIS-Set-Cookies'];
    if (extra) {
      try {
        const decoded = JSON.parse(Buffer.from(String(extra), 'base64').toString('utf8'));
        if (Array.isArray(decoded)) decoded.forEach((c) => { if (typeof c === 'string' && c) jar.push(c); });
      } catch { /* abaikan cookie tambahan yang tidak valid */ }
    }
    if (jar.length) {
      responseHeaders['set-cookie'] = jar;
    }
    res.writeHead(response.httpStatusCode || 200, responseHeaders);
    res.end(payload);
  } catch (error) {
    console.error('[preview] error', error);
    res.writeHead(500, { 'Content-Type': 'text/html; charset=utf-8' });
    res.end(
      '<pre style="font:13px/1.5 monospace;padding:20px;background:#0b2135;color:#ffb4c0;white-space:pre-wrap">' +
        'PHP preview error\n\n' +
        String(error && error.stack ? error.stack : error).replace(/[<>&]/g, (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;' }[c])) +
        '</pre>'
    );
  }
});

server.listen(PORT, HOST, () => {
  console.log(`[preview] HRIS Asia Raya listening on http://${HOST}:${PORT}`);
});

process.on('unhandledRejection', (err) => console.error('[preview] unhandled', err));
